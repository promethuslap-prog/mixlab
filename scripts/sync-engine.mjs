import fs from 'node:fs';

const js = fs.readFileSync(new URL('../src/audio/engine.js', import.meta.url), 'utf8');
if (js.includes('`') || js.includes('${')) {
  console.error('engine.js must not contain backticks or ${ so it can be inlined safely.');
  process.exit(1);
}
const out = `// Generated by scripts/sync-engine.mjs from src/audio/engine.js. Do not edit.\nexport const ENGINE_JS = ${JSON.stringify(js)};\n`;
fs.writeFileSync(new URL('../src/audio/engineSource.ts', import.meta.url), out);
console.log(`Wrote engine source (${js.length} chars).`);
